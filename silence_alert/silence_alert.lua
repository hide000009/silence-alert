-- Silence Alert v1.3.0
-- Plays a ding ONLY when Silence actually lands on an enemy.
--
-- Install:
--   1. Make a folder: Windower4/addons/silence_alert/
--   2. Put silence_alert.lua in it (only file needed; the ding.wav
--      sound is created automatically the first time it loads)
--   3. In game: //lua load silence_alert
--   4. Try it: //sa test  (plays the sound once)
--
-- Commands (//sa ...):
--   test   -- play the sound once, to check it works
--   on     -- enable alerts
--   off    -- disable alerts
--   party  -- toggle: only alert for your own / your party's Silence
--   help   -- show commands
--
-- How it works (strict, to avoid false alarms):
--   * Action check: a Silence spell finishes on a monster AND the
--     result message is the "effect applied" message (236).
--     Resists / no-effect / immune results never ding.
--   * Log check (backup, for the Japanese client): the battle log line
--     "<name> + [silence effect line]" counts only when <name> is
--     really a monster (checked with get_mob_by_name). Barsilence
--     lines, party members, and wear-off lines are ignored.
--     A 1-second debounce stops double dings.
--
-- All chat messages from this addon are in English (ASCII), so they
-- can never garble. The Japanese log patterns below are written as
-- Shift_JIS byte escapes (numbers), so this whole file stays pure
-- ASCII and is safe to save in any encoding.
-- It needs Windower (the `windower` table); plain `lua` cannot run it.

_addon.name = 'Silence Alert'
_addon.author = 'Hide'
_addon.version = '1.3.0'
_addon.command = 'sa'

-- ===== Settings you can tweak =====
local PARTY_ONLY = false      -- true: only your / your party's Silence counts
local USE_TEXT_DETECT = true  -- backup detection from the JP battle log
-- Action-result message that means the debuff was applied.
local APPLIED_MESSAGE = 236
-- ==================================

-- Japanese log patterns as Shift_JIS byte escapes.
local TXT_SILENCE_EFFECT = '\131\84\131\67\131\140\131\88\130\204\140\248\137\202'  -- "sairesu no kouka" (silence effect)
local TXT_BARSILENCE     = '\131\111\131\84\131\67\131\140\131\88'      -- "basairesu" (Barsilence)
local TXT_BARSILENCERA   = '\131\111\131\84\131\67\131\140\131\137'    -- "basairera" (Barsilencera)
local TXT_WORE_OFF       = '\144\216\130\234\130\189'        -- "kireta" (wore off)
local TXT_NO_RECEIVE     = '\142\243\130\175\130\200\130\162'      -- "ukenai" (does not receive)
local TXT_NO_EFFECT      = '\130\200\130\169\130\193\130\189'       -- "nakatta" (had no effect)
local TXT_EFFECT_LINE    = '\130\205\129\65\131\84\131\67\131\140\131\88\130\204\140\248\137\202'     -- "wa, sairesu no kouka" (name + effect line)

local enabled = true
local party_only = PARTY_ONLY
local last_play = 0

local sound_path = 'ding.wav'
if windower.addon_path then
    sound_path = windower.addon_path
    if not sound_path:match('[\\/]$') then
        sound_path = sound_path .. '\\'
    end
    sound_path = sound_path .. 'ding.wav'
end

local function say(msg)
    windower.add_to_chat(207, '[SilenceAlert] ' .. msg)
end

-- The ding sound is generated by this addon if ding.wav is missing,
-- so the addon ships as a single .lua file. (Two-tone ping, G6 then
-- C7, with exponential decay; 44.1kHz 16-bit mono WAV.)
local function u16(n)
    return string.char(n % 256, math.floor(n / 256) % 256)
end

local function u32(n)
    return string.char(n % 256, math.floor(n / 256) % 256, math.floor(n / 65536) % 256, math.floor(n / 16777216) % 256)
end

local function generate_sound(path)
    local rate = 44100
    local frames = math.floor(rate * 0.55)
    local data = {}
    for i = 0, frames - 1 do
        local t = i / rate
        local freq, tt
        if t < 0.18 then
            freq, tt = 1567.98, t
        else
            freq, tt = 2093.00, t - 0.18
        end
        local v = math.floor(math.sin(2 * math.pi * freq * tt) * math.exp(-tt * 14) * 16000)
        if v < 0 then v = v + 65536 end
        data[#data + 1] = string.char(v % 256, math.floor(v / 256) % 256)
    end
    local pcm = table.concat(data)
    local wav = 'RIFF' .. u32(36 + #pcm) .. 'WAVE'
        .. 'fmt ' .. u32(16) .. u16(1) .. u16(1)
        .. u32(rate) .. u32(rate * 2) .. u16(2) .. u16(16)
        .. 'data' .. u32(#pcm) .. pcm
    local f = io.open(path, 'wb')
    if not f then
        return false
    end
    f:write(wav)
    f:close()
    return true
end

local function ensure_sound()
    local f = io.open(sound_path, 'rb')
    if f then
        f:close()
        return
    end
    if not generate_sound(sound_path) then
        say('Could not create ding.wav, so alerts will be message-only.')
    end
end

local function ding()
    local now = os.time()
    if now - last_play < 1 then
        return
    end
    last_play = now
    windower.play_sound(sound_path)
end

-- Resolve the Silence spell ID from Windower's resources, so we do not
-- have to trust a hardcoded number. Fallback: 59.
local silence_ids = {}
do
    local ok, res = pcall(require, 'resources')
    if ok and res and res.spells then
        local s = res.spells:with('english', 'Silence')
        if s and s.id then
            silence_ids[s.id] = true
        end
    end
    if not next(silence_ids) then
        silence_ids[59] = true
    end
end

local function is_party_actor(actor_id)
    local player = windower.ffxi.get_player()
    if player and player.id == actor_id then
        return true
    end
    local party = windower.ffxi.get_party()
    if not party then
        return false
    end
    for _, key in ipairs({ 'p0', 'p1', 'p2', 'p3', 'p4', 'p5' }) do
        local member = party[key]
        if member and member.id == actor_id then
            return true
        end
    end
    return false
end

-- Track spells as they start (category 8), judge them as they finish (category 4).
local casting = {}

windower.register_event('action', function(act)
    if not enabled or not act then
        return
    end

    if act.category == 8 then
        casting[act.actor_id] = act.param
        return
    end
    if act.category ~= 4 then
        return
    end

    local spell_id = nil
    if act.param and silence_ids[act.param] then
        spell_id = act.param
    elseif casting[act.actor_id] and silence_ids[casting[act.actor_id]] then
        spell_id = casting[act.actor_id]
    end
    casting[act.actor_id] = nil

    if not spell_id then
        return
    end
    if party_only and not is_party_actor(act.actor_id) then
        return
    end

    for _, target in ipairs(act.targets or {}) do
        local mob = windower.ffxi.get_mob_by_id(target.id)
        if mob and mob.is_npc then
            for _, action in ipairs(target.actions or {}) do
                if action.message == APPLIED_MESSAGE then
                    ding()
                    say('Silence landed on: ' .. (mob.name or ''))
                    return
                end
            end
        end
    end
end)

-- Backup detector: the Japanese battle log line for a silenced target.
-- Strict: the name in the line must belong to a monster.
windower.register_event('incoming text', function(original)
    if not enabled or not USE_TEXT_DETECT or not original then
        return
    end
    -- Barsilence lines contain the silence-effect words too; exclude them first.
    if original:find(TXT_BARSILENCE, 1, true) or original:find(TXT_BARSILENCERA, 1, true) then
        return
    end
    if not original:find(TXT_SILENCE_EFFECT, 1, true) then
        return
    end
    -- Exclude wear-off / no-effect lines.
    if original:find(TXT_WORE_OFF, 1, true) or original:find(TXT_NO_RECEIVE, 1, true) or original:find(TXT_NO_EFFECT, 1, true) then
        return
    end
    -- Pull out the target name before the effect line.
    local clean = original:gsub('[%z\1-\31]', '')
    local pos = clean:find(TXT_EFFECT_LINE, 1, true)
    if not pos then
        return
    end
    local name = clean:sub(1, pos - 1)
    if name == '' then
        return
    end
    if not windower.ffxi.get_mob_by_name then
        return
    end
    local mob = windower.ffxi.get_mob_by_name(name)
    if mob and mob.is_npc then
        ding()
        say('Silence landed on: ' .. (mob.name or name))
    end
end)

windower.register_event('load', function()
    pcall(ensure_sound)
    say('loaded v' .. _addon.version .. '. Type //sa test to check the sound.')
end)

windower.register_event('addon command', function(command)
    command = (command or ''):lower()
    if command == 'test' then
        last_play = 0
        ding()
        say('Playing the test sound.')
    elseif command == 'on' then
        enabled = true
        say('Alerts ON.')
    elseif command == 'off' then
        enabled = false
        say('Alerts OFF.')
    elseif command == 'party' then
        party_only = not party_only
        say('Party-only alerts: ' .. (party_only and 'ON' or 'OFF'))
    else
        say('Commands: //sa test | on | off | party')
    end
end)
